//! Public A2A protocol data contracts.
//!
//! These types describe the protocol boundary only. They do not own an Agent,
//! Runtime, transport connection, or task storage. HTTP and other transports
//! can serialize them, while the concrete conversion from Heart events lives
//! under `core::protocol::a2a`.

use serde::{Deserialize, Serialize};
use serde_json::{Map, Value};

/// Local identifiers used when converting a Heart run to an A2A task.
#[derive(Clone, Debug, Deserialize, Eq, PartialEq, Serialize)]
pub struct Context {
    pub session_id: i64,
    pub chat_id: i64,
    /// A2A task identifier generated by the server or its task projection.
    /// This is intentionally independent from Heart's local `chat_id`.
    pub task_id: String,
}

impl Context {
    pub fn new(session_id: i64, chat_id: i64, task_id: impl Into<String>) -> Self {
        Self {
            session_id,
            chat_id,
            task_id: task_id.into(),
        }
    }

    pub fn context_id(&self) -> String {
        self.session_id.to_string()
    }

    pub fn task_id(&self) -> String {
        self.task_id.clone()
    }
}

/// A2A content part. The wire representation uses one populated content
/// member (`text`, `raw`, `url`, or `data`) plus optional metadata.
#[derive(Clone, Debug, Deserialize, PartialEq, Serialize)]
pub struct Part {
    #[serde(skip_serializing_if = "Option::is_none")]
    pub text: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub raw: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub url: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub data: Option<Value>,
    #[serde(rename = "mediaType", skip_serializing_if = "Option::is_none")]
    pub media_type: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub filename: Option<String>,
    #[serde(default, skip_serializing_if = "Map::is_empty")]
    pub metadata: Map<String, Value>,
}

impl Part {
    pub fn text(value: impl Into<String>) -> Self {
        Self {
            text: Some(value.into()),
            raw: None,
            url: None,
            data: None,
            media_type: None,
            filename: None,
            metadata: Map::new(),
        }
    }

    pub fn data(value: Value) -> Self {
        Self {
            text: None,
            raw: None,
            url: None,
            data: Some(value),
            media_type: Some("application/json".into()),
            filename: None,
            metadata: Map::new(),
        }
    }
}

#[derive(Clone, Debug, Deserialize, Eq, PartialEq, Serialize)]
pub enum Role {
    #[serde(rename = "ROLE_USER")]
    User,
    #[serde(rename = "ROLE_AGENT")]
    Agent,
}

/// A message exchanged with a remote Agent.
#[derive(Clone, Debug, Deserialize, PartialEq, Serialize)]
pub struct Message {
    pub role: Role,
    pub parts: Vec<Part>,
    #[serde(rename = "messageId")]
    pub message_id: String,
    #[serde(rename = "contextId", skip_serializing_if = "Option::is_none")]
    pub context_id: Option<String>,
    #[serde(rename = "taskId", skip_serializing_if = "Option::is_none")]
    pub task_id: Option<String>,
    #[serde(
        rename = "referenceTaskIds",
        default,
        skip_serializing_if = "Vec::is_empty"
    )]
    pub reference_task_ids: Vec<String>,
    #[serde(default, skip_serializing_if = "Map::is_empty")]
    pub metadata: Map<String, Value>,
}

#[derive(Clone, Debug, Deserialize, Eq, PartialEq, Serialize)]
pub enum TaskState {
    #[serde(rename = "TASK_STATE_SUBMITTED")]
    Submitted,
    #[serde(rename = "TASK_STATE_WORKING")]
    Working,
    #[serde(rename = "TASK_STATE_INPUT_REQUIRED")]
    InputRequired,
    #[serde(rename = "TASK_STATE_AUTH_REQUIRED")]
    AuthRequired,
    #[serde(rename = "TASK_STATE_COMPLETED")]
    Completed,
    #[serde(rename = "TASK_STATE_FAILED")]
    Failed,
    #[serde(rename = "TASK_STATE_CANCELED")]
    Canceled,
    #[serde(rename = "TASK_STATE_REJECTED")]
    Rejected,
}

#[derive(Clone, Debug, Deserialize, PartialEq, Serialize)]
pub struct TaskStatus {
    pub state: TaskState,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub message: Option<Message>,
}

#[derive(Clone, Debug, Deserialize, PartialEq, Serialize)]
pub struct Artifact {
    #[serde(rename = "artifactId")]
    pub artifact_id: String,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub name: Option<String>,
    pub parts: Vec<Part>,
    #[serde(default, skip_serializing_if = "Map::is_empty")]
    pub metadata: Map<String, Value>,
}

#[derive(Clone, Debug, Deserialize, PartialEq, Serialize)]
pub struct Task {
    pub id: String,
    #[serde(rename = "contextId")]
    pub context_id: String,
    pub status: TaskStatus,
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub artifacts: Vec<Artifact>,
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub history: Vec<Message>,
}

#[derive(Clone, Debug, Deserialize, PartialEq, Serialize)]
pub struct TaskStatusUpdateEvent {
    #[serde(rename = "taskId")]
    pub task_id: String,
    #[serde(rename = "contextId")]
    pub context_id: String,
    pub status: TaskStatus,
    #[serde(default, skip_serializing_if = "Map::is_empty")]
    pub metadata: Map<String, Value>,
}

#[derive(Clone, Debug, Deserialize, PartialEq, Serialize)]
pub struct TaskArtifactUpdateEvent {
    #[serde(rename = "taskId")]
    pub task_id: String,
    #[serde(rename = "contextId")]
    pub context_id: String,
    pub artifact: Artifact,
    pub append: bool,
    #[serde(rename = "lastChunk")]
    pub last_chunk: bool,
    #[serde(default, skip_serializing_if = "Map::is_empty")]
    pub metadata: Map<String, Value>,
}

/// One item in an A2A streaming response.
#[derive(Clone, Debug, Deserialize, PartialEq, Serialize)]
#[serde(rename_all = "camelCase", rename_all_fields = "camelCase")]
pub enum StreamResponse {
    Task(Task),
    Message(Message),
    #[serde(rename = "statusUpdate")]
    TaskStatusUpdateEvent(TaskStatusUpdateEvent),
    #[serde(rename = "artifactUpdate")]
    TaskArtifactUpdateEvent(TaskArtifactUpdateEvent),
}

#[derive(Clone, Debug, Deserialize, PartialEq, Serialize)]
pub struct SendMessageRequest {
    pub message: Message,
    #[serde(default, skip_serializing_if = "Map::is_empty")]
    pub metadata: Map<String, Value>,
}

#[derive(Clone, Debug, Deserialize, PartialEq, Serialize)]
pub struct AgentCapabilities {
    #[serde(default)]
    pub streaming: bool,
    #[serde(rename = "pushNotifications", default)]
    pub push_notifications: bool,
    #[serde(rename = "stateTransitionHistory", default)]
    pub state_transition_history: bool,
}

#[derive(Clone, Debug, Deserialize, PartialEq, Serialize)]
pub struct Skill {
    pub id: String,
    pub name: String,
    pub description: String,
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub tags: Vec<String>,
}

/// Description published by an A2A server for discovery.
#[derive(Clone, Debug, Deserialize, PartialEq, Serialize)]
pub struct AgentCard {
    pub name: String,
    pub description: String,
    pub url: String,
    pub version: String,
    pub capabilities: AgentCapabilities,
    #[serde(
        rename = "defaultInputModes",
        default,
        skip_serializing_if = "Vec::is_empty"
    )]
    pub default_input_modes: Vec<String>,
    #[serde(
        rename = "defaultOutputModes",
        default,
        skip_serializing_if = "Vec::is_empty"
    )]
    pub default_output_modes: Vec<String>,
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub skills: Vec<Skill>,
}
