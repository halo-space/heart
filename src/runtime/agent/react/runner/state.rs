//! Mutable state for one ReAct run.
//!
//! The runner drives this state, while checkpoint serialization continues to
//! use the canonical Agent State. Keeping the live machine in its own private
//! module makes the event loop easier to inspect without creating another
//! persistence model.

use super::*;

pub(crate) struct ReActState<M: Chat> {
    pub(crate) completion: Option<crate::runtime::agent::completion::State>,
    pub(crate) restored_output: Option<Event>,
    pub(crate) replayed_completion: bool,
    pub(crate) preparation: Option<crate::runtime::agent::preparation::State>,
    pub(crate) _interaction_owner: Option<crate::runtime::agent::reply::Owner>,
    pub(crate) interaction: Option<crate::runtime::agent::reply::Handle>,
    pub(crate) waits: Vec<crate::runtime::agent::wait::Wait>,
    pub(crate) stream: bool,
    pub(crate) model: std::sync::Arc<M>,
    pub(crate) dispatch: std::sync::Arc<Dispatch>,
    pub(crate) subagents: std::sync::Arc<Vec<SubAgent>>,
    pub(crate) handoff_targets: std::sync::Arc<Vec<String>>,
    pub(crate) team_mode: bool,
    pub(crate) max_iters: usize,
    pub(crate) max_concurrency: usize,
    pub(crate) cancellation: Cancellation,
    pub(crate) cancellation_waiter: Option<crate::cancellation::Registration>,
    pub(crate) messages: Messages,
    /// Every planned task shares the run's model-call budget.
    pub(crate) iteration: Arc<AtomicUsize>,
    pub(crate) task_base: Messages,
    pub(crate) provider: Option<Pin<Box<M::Stream>>>,
    pub(crate) query: Input,
    pub(crate) graph: Option<Graph>,
    pub(crate) resume_nodes: BTreeSet<String>,
    pub(crate) external_resume_nodes: BTreeSet<String>,
    pub(crate) id_fn: Option<fn() -> i64>,
    pub(crate) checkpoint: Option<CheckpointSave>,
    pub(crate) checkpoint_id: Option<i64>,
    pub(crate) plan_execution: bool,
    pub(crate) active_tasks:
        FuturesUnordered<Pin<Box<dyn Future<Output = TaskProgress<M>> + Send + 'static>>>,
    pub(crate) task_runs: BTreeMap<String, execution::Active>,
    pub(crate) task_slots: Arc<tokio::sync::Semaphore>,
    pub(crate) task_ready: Arc<futures_util::task::AtomicWaker>,
    pub(crate) task_error: Option<Error>,
    pub(crate) dispatch_failed: bool,
    pub(crate) is_plan_task: bool,
    pub(crate) tool_slots: Arc<tokio::sync::Semaphore>,
    pub(crate) plan_finalizing: bool,
    pub(crate) pending_plans: VecDeque<(usize, Call)>,
    pub(crate) planning: Option<Planning>,
    pub(crate) pending_replan: Option<Evaluation>,
    pub(crate) plan_result: Option<Message>,
    pub(crate) planning_error: Option<Error>,
    pub(crate) resume_input: Option<Input>,
    pub(crate) pending_calls: VecDeque<(usize, Call)>,
    pub(crate) active_tools:
        FuturesUnordered<Pin<Box<dyn Future<Output = ToolProgress> + Send + 'static>>>,
    pub(crate) tool_progress: VecDeque<ToolProgress>,
    pub(crate) child_events: VecDeque<Result<Event, Error>>,
    pub(crate) child_relay: crate::runtime::agent::subagent::Relay,
    pub(crate) pending_subagents: BTreeMap<String, PendingSubAgent>,
    pub(crate) tool_results: BTreeMap<usize, Message>,
    pub(crate) evaluations: BTreeMap<String, ToolEvaluation>,
    pub(crate) steps: Vec<Step>,
    pub(crate) child_nodes: BTreeMap<String, crate::runtime::agent::node::State>,
    pub(crate) child_nodes_dirty: bool,
    pub(crate) feedback_dirty: bool,
    pub(crate) phase_progress: bool,
    pub(crate) root: crate::runtime::agent::subagent::Root,
    pub(crate) partial: Message,
    pub(crate) done: bool,
    pub(crate) hooks: Hooks,
    pub(crate) access: Access,
    pub(crate) evaluator: Option<EvaluatorHandle>,
    pub(crate) metadata: Map<String, Value>,
    pub(crate) run: Execute,
    pub(crate) model_pending: bool,
    pub(crate) model_settled: bool,
    pub(crate) input_tokens: u64,
    pub(crate) request: Option<Box<Request>>,
    pub(crate) trace: Root,
    pub(crate) model_span: Option<SpanScope>,
}
